#!/usr/bin/env python3
"""Copy the modules the renewal add-on needs into xpeng_renew/vendor/.

An add-on's build context is its own folder, so the code it runs has to live there.
Rather than hand-copying (and drifting), this mirrors the repo layout under vendor/:

    vendor/custom_components/xpeng/<login modules>
    vendor/tools/onboard_email_login.py, guardian_token.mjs

so `python3 vendor/tools/onboard_email_login.py ...` behaves exactly like a repo
checkout: the tool walks up from itself and finds the component.

Run it after changing any of those files, and re-run `docker build`/the add-on
update. tests/test_renew_vendor_sync.py fails if the copies are stale.
"""

from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
VENDOR = REPO / "xpeng_renew" / "vendor"
COMPONENT_FILES = [
    "xpeng_api.py",
    "xpeng_login.py",
    "xpeng_errors.py",
    "const.py",
    "guardian.py",
]
TOOL_FILES = ["onboard_email_login.py", "guardian_token.mjs"]


def _needed_constants(vendor: Path) -> set[str]:
    """Every ``const.NAME`` and ``from .const import NAME`` the vendored code uses."""
    needed: set[str] = set()
    for path in list(vendor.rglob("*.py")):
        text = path.read_text(encoding="utf-8")
        needed |= set(re.findall(r"const\.([A-Z][A-Z0-9_]*)", text))
        for block in re.findall(r"from \.const import \(([^)]*)\)", text):
            needed |= set(re.findall(r"([A-Z][A-Z0-9_]*)", block))
        for line in re.findall(r"from \.const import ([^\n(]+)", text):
            needed |= set(re.findall(r"([A-Z][A-Z0-9_]*)", line))
    return needed


def write_trimmed_const(needed: set[str]) -> list[str]:
    """Emit a const.py with only those constants.

    The real const.py imports Home Assistant for its entity descriptions, which the
    add-on neither has nor needs: it drives the login code and talks to Home
    Assistant over HTTP. Copying it verbatim would make every import fail, so the
    simple assignments are extracted instead - and a missing one is a hard error
    rather than a surprise at runtime.
    """
    import ast

    source_path = REPO / "custom_components" / "xpeng" / "const.py"
    source = source_path.read_text(encoding="utf-8")
    tree = ast.parse(source)
    found: dict[str, str] = {}
    for node in tree.body:
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            target = node.target.id
        elif isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(
            node.targets[0], ast.Name
        ):
            target = node.targets[0].id
        else:
            continue
        if target in needed:
            segment = ast.get_source_segment(source, node)
            if segment:
                found[target] = segment

    missing = sorted(needed - set(found))
    if missing:
        raise SystemExit(
            "these constants are referenced by the add-on code but are not simple "
            f"assignments in const.py, so they cannot be vendored: {missing}"
        )

    dst = VENDOR / "custom_components" / "xpeng" / "const.py"
    header = (
        '"""Trimmed copy of const.py for the renewal add-on - generated by\n'
        "tools/sync_renew_vendor.py. Do not edit; edit the real const.py.\n\n"
        "Only the constants the login code uses are kept: the real module imports\n"
        "Home Assistant for its entity descriptions, and this add-on has no reason\n"
        'to carry Home Assistant at all.\n"""\n\n'
        "from __future__ import annotations\n\nfrom typing import Final\n\n"
    )
    body = "\n\n".join(found[name] for name in sorted(found))
    dst.write_text(header + body + "\n", encoding="utf-8")
    return [str(dst.relative_to(REPO))]


def main() -> int:
    written = []
    for name in COMPONENT_FILES:
        if name == "const.py":
            continue
        src = REPO / "custom_components" / "xpeng" / name
        dst = VENDOR / "custom_components" / "xpeng" / name
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        written.append(dst.relative_to(REPO))
    for name in TOOL_FILES:
        src = REPO / "tools" / name
        dst = VENDOR / "tools" / name
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        written.append(dst.relative_to(REPO))
    written += write_trimmed_const(_needed_constants(VENDOR))
    for path in written:
        print(f"  synced {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
